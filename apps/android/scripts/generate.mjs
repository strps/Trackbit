// Colors: the web's oklch tokens → sRGB
// ---------------------------------------------------------------------------------------------

/** oklch(L C H [/ A]) → [r, g, b, a], sRGB channels 0–255 clipped to the gamut. */
function oklchToRgba(value) {
    const m = /^oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)(%?))?\s*\)$/.exec(value);
    if (!m) fail(`Unsupported color "${value}"`);
    const l = Number(m[1]) / (m[2] ? 100 : 1);
    const c = Number(m[3]);
    const h = (Number(m[4]) * Math.PI) / 180;
    const alpha = m[5] === undefined ? 1 : Number(m[5]) / (m[6] ? 100 : 1);

    const a = c * Math.cos(h);
    const b = c * Math.sin(h);
    const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3;
    const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3;
    const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3;
    const linear = [
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
    ];
    const gamma = (x) => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055);
    const rgb = linear.map((x) => Math.round(Math.min(1, Math.max(0, gamma(x))) * 255));
    return [...rgb, Math.round(alpha * 255)];
}

function cssTokens(css, selector) {
    const start = css.search(new RegExp(`(^|\\n)${selector.replace('.', '\\.')}\\s*\\{`));
    if (start < 0) fail(`${selector} block not found in index.css`);
    const block = css.slice(start, css.indexOf('}', start));
    return Object.fromEntries([...block.matchAll(/--([\w-]+):\s*(oklch\([^)]*\))/g)].map((m) => [m[1], m[2]]));
}

function generateColors() {
    const css = readFileSync(join(FRONTEND, 'src/index.css'), 'utf8');
    const argb = ([r, g, b, a]) => `0x${[a, r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase()}`;
    const camel = (token) => token.replace(/-(\w)/g, (_, c) => c.toUpperCase());
    const light = cssTokens(css, ':root');
    const dark = cssTokens(css, '.dark');
    const names = Object.keys(light);
    const mismatch = [...names.filter((t) => !(t in dark)), ...Object.keys(dark).filter((t) => !(t in light))];
    if (mismatch.length) fail(`:root and .dark define different tokens: ${mismatch}`);
    const palette = (name, tokens) => [
        `internal val ${name} = WebPalette(`,
        ...names.map((token) => `    ${camel(token)} = Color(${argb(oklchToRgba(tokens[token]))}), // ${tokens[token]}`),
        ')',
    ];
    const source = [
        `// ${GENERATED_BY} Source: apps/frontend/src/index.css.`,
        'package com.trackbit.core.designsystem.theme',
        '',
        'import androidx.compose.ui.graphics.Color',
        '',
        '/** The web app\'s shadcn tokens, converted from oklch to sRGB. [TrackbitTheme] maps them onto Material 3 roles. */',
        'internal data class WebPalette(',
        ...names.map((token) => `    val ${camel(token)}: Color,`),
        ')',
        '',
        ...palette('WebLight', light),
        '',
        ...palette('WebDark', dark),
        '',
    ].join('\n');
    return { [join(DESIGNSYSTEM, 'kotlin/com/trackbit/core/designsystem/theme/WebColors.kt')]: source };
}

