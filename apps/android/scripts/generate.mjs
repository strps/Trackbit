// Strings: ICU messages → Android string resources
// ---------------------------------------------------------------------------------------------

/** `tracker` + `list.items_count` → `tracker_list_items_count`. */
function resourceName(namespace, key) {
    const name = `${namespace}_${key}`.replace(/[.-]/g, '_');
    if (!/^[a-z][a-z0-9_]*$/.test(name)) fail(`"${namespace}:${key}" doesn't make a valid resource name (${name})`);
    return name;
}

/**
 * Splits an ICU message into text and `{…}` parts, honouring nested braces. ICU's `''` is a
 * literal apostrophe; a lone `'` is literal too (i18next-icu's default apostrophe mode).
 */
function tokenize(message) {
    const parts = [];
    let text = '';
    for (let i = 0; i < message.length; i++) {
        const ch = message[i];
        if (ch === "'" && message[i + 1] === "'") {
            text += "'";
            i++;
        } else if (ch === '{') {
            let depth = 1;
            let j = i + 1;
            for (; j < message.length && depth > 0; j++) {
                if (message[j] === '{') depth++;
                if (message[j] === '}') depth--;
            }
            if (depth > 0) fail(`Unbalanced braces in "${message}"`);
            if (text) parts.push({ text });
            text = '';
            parts.push({ arg: message.slice(i + 1, j - 1) });
            i = j - 1;
        } else {
            text += ch;
        }
    }
    if (text) parts.push({ text });
    return parts;
}

/** Android string-resource escaping for literal text. `%` is doubled only in format strings. */
function escapeText(text, formatted) {
    let out = text
        .replace(/\\/g, '\\\\')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/'/g, "\\'")
        .replace(/"/g, '\\"')
        .replace(/\n/g, '\\n');
    if (formatted) out = out.replace(/%/g, '%%');
    return out;
}

const escapeLeading = (s) => (/^[@?]/.test(s) ? `\\${s}` : s);

const PLURAL_QUANTITIES = new Set(['zero', 'one', 'two', 'few', 'many', 'other']);

/** Parses `count, plural, one {…} other {…}` into its variable and branches. */
function parsePlural(arg) {
    const match = /^\s*(\w+)\s*,\s*plural\s*,(.*)$/s.exec(arg);
    if (!match) return null;
    const [, variable, body] = match;
    const branches = {};
    let selector;
    for (const part of tokenize(body)) {
        if (part.text !== undefined) {
            for (const quantity of part.text.trim().split(/\s+/).filter(Boolean)) {
                if (!PLURAL_QUANTITIES.has(quantity)) fail(`Plural selector "${quantity}" has no Android equivalent in {${arg}}`);
                selector = quantity;
            }
        } else {
            if (!selector) fail(`Plural branch without a selector in {${arg}}`);
            branches[selector] = part.arg;
            selector = undefined;
        }
    }
    if (!branches.other) fail(`Plural {${arg}} needs an "other" branch`);
    return { variable, branches };
}

/**
 * Converts one ICU message. Arguments become positional `%N$s` in order of first appearance;
 * `#` inside a plural becomes the count as `%N$d`.
 */
function convertMessage(message, where) {
    const parts = tokenize(message);
    const plurals = parts.filter((p) => p.arg !== undefined && parsePlural(p.arg));
    if (plurals.length > 1) fail(`${where}: more than one plural in a message`);
    if (plurals.length === 1 && parts.length > 1) fail(`${where}: a plural must be the whole message`);

    const order = [];
    const index = (name) => {
        if (!/^\w+$/.test(name)) fail(`${where}: unsupported ICU argument {${name}}`);
        if (!order.includes(name)) order.push(name);
        return order.indexOf(name) + 1;
    };

    const render = (tokens, formatted, countVariable) =>
        tokens
            .map((p) => {
                if (p.text !== undefined) {
                    if (countVariable === undefined) return escapeText(p.text, formatted);
                    return p.text
                        .split('#')
                        .map((t) => escapeText(t, formatted))
                        .join(`%${index(countVariable)}$d`);
                }
                return `%${index(p.arg.trim())}$s`;
            })
            .join('');

    if (plurals.length === 1) {
        const { variable, branches } = parsePlural(plurals[0].arg);
        index(variable);
        const items = Object.fromEntries(
            Object.entries(branches).map(([q, body]) => [q, escapeLeading(render(tokenize(body), true, variable))]),
        );
        return { plural: items };
    }
    const formatted = parts.some((p) => p.arg !== undefined);
    return { text: escapeLeading(render(parts, formatted)), formatted };
}

function readLocale(locale) {
    const dir = join(LOCALES_DIR, locale);
    const entries = [];
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
        const namespace = file.replace(/\.json$/, '');
        const bundle = JSON.parse(readFileSync(join(dir, file), 'utf8'));
        for (const [key, value] of Object.entries(bundle)) {
            if (typeof value !== 'string') fail(`${locale}/${file}: "${key}" is not a string (nested keys aren't supported)`);
            entries.push({ name: resourceName(namespace, key), value, where: `${locale}/${file} "${key}"` });
        }
    }
    const seen = new Set();
    for (const { name, where } of entries) {
        if (seen.has(name)) fail(`${where} collides with another key as ${name}`);
        seen.add(name);
    }
    return entries;
}

function stringsXml(entries) {
    const lines = entries.map(({ name, value, where }) => {
        const converted = convertMessage(value, where);
        if (converted.plural) {
            const items = Object.entries(converted.plural).map(([q, t]) => `        <item quantity="${q}">${t}</item>`);
            return [`    <plurals name="${name}">`, ...items, '    </plurals>'].join('\n');
        }
        const notFormatted = !converted.formatted && converted.text.includes('%') ? ' formatted="false"' : '';
        return `    <string name="${name}"${notFormatted}>${converted.text}</string>`;
    });
    return [
        '<?xml version="1.0" encoding="utf-8"?>',
        `<!-- ${GENERATED_BY} Source: apps/frontend/src/i18n/locales. -->`,
        // The web's copy is the source of truth, so its typography stays as it is, and features
        // pick strings from this catalogue over time.
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,TypographyEllipsis">',
        ...lines,
        '</resources>',
        '',
    ].join('\n');
}

function generateStrings() {
    const locales = readdirSync(LOCALES_DIR).filter((d) => existsSync(join(LOCALES_DIR, d, 'common.json'))).sort();
    const reference = new Set(readLocale(DEFAULT_LOCALE).map((e) => e.name));
    const outputs = {};
    for (const locale of locales) {
        const entries = readLocale(locale);
        const names = new Set(entries.map((e) => e.name));
        const missing = [...reference].filter((n) => !names.has(n));
        const extra = [...names].filter((n) => !reference.has(n));
        if (missing.length || extra.length) {
            fail(`Locale "${locale}" doesn't match "${DEFAULT_LOCALE}": missing [${missing}], extra [${extra}]`);
        }
        const dir = locale === DEFAULT_LOCALE ? 'values' : `values-${locale}`;
        outputs[join(ANDROID, 'core/i18n/src/main/res', dir, 'strings.xml')] = stringsXml(entries);
    }
    outputs[join(ANDROID, 'core/i18n/src/main/res/xml/locales_config.xml')] = localeConfigXml(locales);
    return outputs;
}

/** The languages the system's per-app language setting offers: those the strings ship in. */
function localeConfigXml(locales) {
    return [
        '<?xml version="1.0" encoding="utf-8"?>',
        `<!-- ${GENERATED_BY} Source: apps/frontend/src/i18n/locales. -->`,
        '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">',
        ...locales.map((locale) => `    <locale android:name="${locale}" />`),
        '</locale-config>',
        '',
    ].join('\n');
}

