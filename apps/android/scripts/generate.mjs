async function loadTypes() {
    const dist = join(REPO, 'packages/types/dist/index.js');
    if (!existsSync(dist)) fail('packages/types/dist is missing: run `pnpm --filter @trackbit/types build` first');
    return import(pathToFileURL(dist).href);
}

const pascal = (id) => id.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
const kotlinFloat = (n) => `${n}f`;

function generatePresets(types) {
    const entries = types.COLOR_THEMES.map((theme) => {
        const stops = types.GRADIENT_PRESET_STOPS[theme].map(({ position, color }) => {
            const channels = color.map(kotlinFloat).join(', ');
            return `        ColorStop(${kotlinFloat(position)}, Rgba(${channels})),`;
        });
        return [`    ColorTheme.${pascal(theme)} to listOf(`, ...stops, '    ),'].join('\n');
    });
    const source = [
        `// ${GENERATED_BY} Source: GRADIENT_PRESET_STOPS in @trackbit/types.`,
        'package com.trackbit.core.model',
        '',
        '/** Each preset theme\'s heatmap gradient. [ColorTheme.Custom]\'s is the default for a new custom gradient. */',
        'val GradientPresets: Map<ColorTheme, List<ColorStop>> = mapOf(',
        ...entries,
        ')',
        '',
    ].join('\n');
    return { [join(MODEL_SRC, 'GradientPresets.kt')]: source };
}

/** The wire strings of a handwritten `enum class <name>` in core:model's Enums.kt. */
function enumWires(name) {
    const source = readFileSync(join(MODEL_SRC, 'Enums.kt'), 'utf8');
    const body = new RegExp(`enum class ${name}\\b[^{]*\\{([\\s\\S]*?);`).exec(source)?.[1];
    if (!body) fail(`enum class ${name} not found in Enums.kt`);
    return [...body.matchAll(/\w+\("([^"]+)"\)/g)].map((m) => m[1]);
}

function checkEnums(types) {
    for (const [name, expected] of [['HabitIcon', types.HABIT_ICON_IDS], ['ColorTheme', types.COLOR_THEMES]]) {
        const actual = enumWires(name);
        const missing = expected.filter((v) => !actual.includes(v));
        const extra = actual.filter((v) => !expected.includes(v));
        if (missing.length || extra.length) {
            fail(`core:model ${name} doesn't match @trackbit/types: missing [${missing}], extra [${extra}]`);
        }
    }
}

