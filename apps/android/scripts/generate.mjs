/** `book: { icon: BookOpen, … }` pairs from the web's icon registry. */
function webIconComponents(ids) {
    const source = readFileSync(join(FRONTEND, 'src/features/habits-configuration/habit-icons.ts'), 'utf8');
    const components = Object.fromEntries([...source.matchAll(/(\w+):\s*\{\s*icon:\s*(\w+)/g)].map((m) => [m[1], m[2]]));
    const missing = ids.filter((id) => !components[id]);
    if (missing.length) fail(`habit-icons.ts has no icon for [${missing}]`);
    return components;
}

/** lucide-react component name → the file its icon node lives in (aliases included). */
function lucideFiles(lucideDir) {
    const index = readFileSync(join(lucideDir, 'dist/esm/lucide-react.js'), 'utf8');
    const files = {};
    for (const m of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([\w-]+)\.js'/g)) {
        for (const alias of m[1].matchAll(/default as (\w+)/g)) files[alias[1]] = m[2];
    }
    return files;
}

const num = (v) => Number(v);
const fmt = (n) => String(Math.round(n * 1000) / 1000);

/** One lucide element as VectorDrawable path data. */
function pathData([tag, attrs]) {
    switch (tag) {
        case 'path':
            return attrs.d;
        case 'circle': {
            const [cx, cy, r] = [attrs.cx, attrs.cy, attrs.r].map(num);
            return `M${fmt(cx - r)},${fmt(cy)}a${fmt(r)},${fmt(r)} 0 1,0 ${fmt(2 * r)},0a${fmt(r)},${fmt(r)} 0 1,0 ${fmt(-2 * r)},0`;
        }
        case 'ellipse': {
            const [cx, cy, rx, ry] = [attrs.cx, attrs.cy, attrs.rx, attrs.ry].map(num);
            return `M${fmt(cx - rx)},${fmt(cy)}a${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(2 * rx)},0a${fmt(rx)},${fmt(ry)} 0 1,0 ${fmt(-2 * rx)},0`;
        }
        case 'rect': {
            const [x, y, w, h] = [attrs.x ?? 0, attrs.y ?? 0, attrs.width, attrs.height].map(num);
            const rx = Math.min(num(attrs.rx ?? attrs.ry ?? 0), w / 2);
            const ry = Math.min(num(attrs.ry ?? attrs.rx ?? 0), h / 2);
            if (!rx && !ry) return `M${fmt(x)},${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}z`;
            const arc = (dx, dy) => `a${fmt(rx)},${fmt(ry)} 0 0,1 ${fmt(dx)},${fmt(dy)}`;
            return (
                `M${fmt(x + rx)},${fmt(y)}h${fmt(w - 2 * rx)}${arc(rx, ry)}v${fmt(h - 2 * ry)}${arc(-rx, ry)}` +
                `h${fmt(-(w - 2 * rx))}${arc(-rx, -ry)}v${fmt(-(h - 2 * ry))}${arc(rx, -ry)}z`
            );
        }
        case 'line':
            return `M${attrs.x1},${attrs.y1}L${attrs.x2},${attrs.y2}`;
        case 'polyline':
        case 'polygon':
            return `M${attrs.points.trim().replace(/\s+/g, ' ')}${tag === 'polygon' ? 'z' : ''}`;
        default:
            return fail(`Unsupported lucide element <${tag}>`);
    }
}

function vectorXml(node, source) {
    const paths = node.map((element) => [
        '    <path',
        `        android:pathData="${pathData(element)}"`,
        '        android:strokeColor="#FF000000"',
        '        android:strokeWidth="2"',
        '        android:strokeLineCap="round"',
        '        android:strokeLineJoin="round" />',
    ].join('\n'));
    return [
        `<!-- ${GENERATED_BY} Source: lucide ${source} (ISC). Tint it; the stroke is black. -->`,
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp"',
        '    android:height="24dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24">',
        ...paths,
        '</vector>',
        '',
    ].join('\n');
}

async function generateIcons(types) {
    const lucideDir = join(FRONTEND, 'node_modules/lucide-react');
    if (!existsSync(lucideDir)) fail('apps/frontend/node_modules/lucide-react is missing: run `pnpm install` first');
    const components = webIconComponents(types.HABIT_ICON_IDS);
    const files = lucideFiles(lucideDir);
    const icons = [
        ...types.HABIT_ICON_IDS.map((id) => [`${ICON_PREFIX}${id}`, components[id]]),
        ...Object.entries(UI_ICONS).map(([name, component]) => [`${UI_ICON_PREFIX}${name}`, component]),
    ];
    const outputs = {};
    for (const [drawable, component] of icons) {
        const file = files[component] ?? fail(`lucide-react has no icon named ${component}`);
        const { __iconNode } = await import(pathToFileURL(join(lucideDir, 'dist/esm/icons', `${file}.js`)).href);
        outputs[join(DRAWABLE_DIR, `${drawable}.xml`)] = vectorXml(__iconNode, file);
    }
    return outputs;
}

// ---------------------------------------------------------------------------------------------

async function main() {
    const check = process.argv.includes('--check');
    const types = await loadTypes();
    checkEnums(types);
    const outputs = {
        ...generateStrings(),
        ...generatePresets(types),
        ...generateColors(),
        ...(await generateIcons(types)),
    };

    const stale = existsSync(DRAWABLE_DIR)
        ? readdirSync(DRAWABLE_DIR)
              .filter((f) => f.startsWith(ICON_PREFIX) || f.startsWith(UI_ICON_PREFIX))
              .map((f) => join(DRAWABLE_DIR, f))
              .filter((path) => !(path in outputs))
        : [];
    const changed = Object.entries(outputs).filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content);

    if (check) {
        const problems = [...changed.map(([p]) => `out of date: ${relative(REPO, p)}`), ...stale.map((p) => `stale: ${relative(REPO, p)}`)];
        if (problems.length) {
            console.error(`${problems.join('\n')}\nRun \`pnpm android:generate\` and commit the result.`);
            process.exit(1);
        }
        console.log(`All ${Object.keys(outputs).length} generated files are up to date.`);
        return;
    }
    for (const [path, content] of changed) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, content);
    }
    for (const path of stale) rmSync(path);
    console.log(`Wrote ${changed.length} of ${Object.keys(outputs).length} files${stale.length ? `, removed ${stale.length}` : ''}.`);
}

main().catch((error) => {
    console.error(error instanceof GenerateError ? `generate: ${error.message}` : error);
    process.exit(1);
});
